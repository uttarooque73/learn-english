import { afterEach, describe, expect, it, vi } from "vitest";
import { POST } from "@/app/api/micro-lessons/route";

afterEach(() => {
  vi.unstubAllGlobals();
  vi.restoreAllMocks();
});

describe("POST /api/micro-lessons", () => {
  it("rejects missing correction data without calling Ollama", async () => {
    const fetchMock = vi.fn();
    vi.stubGlobal("fetch", fetchMock);
    const response = await POST(new Request("http://localhost/api/micro-lessons", {
      method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ original: "I goes" }),
    }));
    expect(response.status).toBe(400);
    expect(fetchMock).not.toHaveBeenCalled();
  });

  it("returns exactly three distinct structured questions generated by Ollama", async () => {
    const questions = [
      { prompt: "Choose the natural version.", options: ["She goes to work.", "She go to work.", "She going to work."], answer: "She goes to work.", explanation: "Use -s with he, she, or it in the present simple." },
      { prompt: "Complete: He ___ every day.", options: ["practise", "practises", "practising"], answer: "practises", explanation: "The third-person singular form takes -s." },
      { prompt: "Choose the correct sentence.", options: ["My brother work here.", "My brother works here.", "My brother working here."], answer: "My brother works here.", explanation: "Use the third-person singular form for one person." },
    ];
    const fetchMock = vi.fn().mockResolvedValue(Response.json({ message: { content: JSON.stringify({ questions }) } }));
    vi.stubGlobal("fetch", fetchMock);
    const response = await POST(new Request("http://localhost/api/micro-lessons", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ original: "She go to work.", improved: "She goes to work.", reason: "Use -s with she in the present simple." }),
    }));
    expect(response.status).toBe(200);
    await expect(response.json()).resolves.toEqual({ questions });
    const [, options] = fetchMock.mock.calls[0] as [string, RequestInit];
    expect(JSON.parse(String(options.body))).toMatchObject({ model: "llama3.1:8b", stream: false, format: "json" });
  });

  it("rejects malformed AI output instead of showing a broken quiz", async () => {
    vi.stubGlobal("fetch", vi.fn().mockResolvedValue(Response.json({ message: { content: JSON.stringify({ questions: [{ prompt: "Only one" }] }) } })));
    const response = await POST(new Request("http://localhost/api/micro-lessons", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ original: "I goes", improved: "I go", reason: "Subject-verb agreement." }),
    }));
    expect(response.status).toBe(502);
  });
});
